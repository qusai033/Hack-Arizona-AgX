"""Convert the Census 2025 1:20m state KML archive into bundled map geometry.

Usage: python3 scripts/import-state-boundaries.py /path/to/cb_2025_us_state_20m.zip
Download: https://www2.census.gov/geo/tiger/GENZ2025/kml/cb_2025_us_state_20m.zip
No geometry is invented, simplified further, or repositioned by this conversion.
"""
import hashlib
import json
from pathlib import Path
import sys
import xml.etree.ElementTree as ET
import zipfile

archive = Path(sys.argv[1])
ns = {"k": "http://www.opengis.net/kml/2.2"}
with zipfile.ZipFile(archive) as z:
    root = ET.fromstring(z.read(next(n for n in z.namelist() if n.endswith('.kml'))))
states = []
names = {"California": "CA", "Arizona": "AZ", "Nevada": "NV", "Utah": "UT"}
for place in root.findall('.//k:Placemark', ns):
    name = place.findtext('.//k:SimpleData[@name="NAME"]', namespaces=ns)
    if name not in names:
        continue
    rings = []
    for ring in place.findall('.//k:Polygon//k:LinearRing/k:coordinates', ns):
        rings.append([[float(v) for v in point.split(',')[:2]] for point in ring.text.split()])
    states.append({"id": names[name], "name": name, "rings": rings})
assert len(states) == 4, 'Expected CA, AZ, NV, and UT in Census KML'
states.sort(key=lambda state: state['id'])
target = Path(__file__).resolve().parents[1] / 'frontend/region-boundaries.js'
target.write_text('// Generated by scripts/import-state-boundaries.py. Census 2025, 1:20m.\n'
                  '// Source archive SHA-256: ' + hashlib.sha256(archive.read_bytes()).hexdigest() + '\n'
                  'export const REGION_STATES = ' + json.dumps(states, separators=(',', ':')) + ';\n')
print(f'Wrote {target.name}: {target.stat().st_size} bytes')
